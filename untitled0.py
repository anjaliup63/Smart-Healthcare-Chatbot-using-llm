def emergency_label(text):
    text = str(text).lower()

    keywords = [
        "chest pain", "bleeding", "breathless",
        "unconscious", "fainting", "seizure",
        "stroke", "heart attack"
    ]

    for word in keywords:
        if word in text:
            return "Emergency"

    return "General"

