#Text preprocessing (LABEL WORD LEAKAGE REMOVAL)
stop_words = set(stopwords.words('english'))
label_words = ['diabetes', 'cancer', 'heart', 'asthma', 'lung', 'eye', 'glaucoma']

def clean_text(text):
    text = text.lower()
    for lw in label_words:
        text = text.replace(lw, '')
    text = re.sub(r'[^a-z ]', '', text)
    words = text.split()
    words = [w for w in words if w not in stop_words]
    return " ".join(words)

df['clean_question'] = df['question'].apply(clean_text)

# 6 TF-IDF Feature Extraction (strict settings)
vectorizer = TfidfVectorizer(
    max_features=6000,
    ngram_range=(1,2),
    min_df=5,
    max_df=0.9
)

X = vectorizer.fit_transform(df['clean_question'])
y = df['manual_label']

# 7 Train-test split
X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.25,
    random_state=42,
    stratify=y
)

# 8. Model training
model = LogisticRegression(
    max_iter=3000,
    class_weight='balanced',
    C=0.5
)

model.fit(X_train, y_train)


# 9. Prediction & accuracy
y_pred = model.predict(X_test)
accuracy = accuracy_score(y_test, y_pred)
